/** Позитивные новости в региональных СМИ в основном «обычные хорошие», а не «восторженные»: их вес приглушён. */
const POSITIVE_DAMP = 0.9;
const REPEAT_DAMP = 0.3;

interface Rule {
  stem: string;
  exact: boolean;
  weight: number;
}
const RULES: Rule[] = GROUPS.flatMap(([weight, words]) =>
  words
    .split(/\s+/)
    .filter(Boolean)
    .map((w): Rule => ({ stem: normalize(w.replace(/=$/, '')), exact: w.endsWith('='), weight })),
);

const PHRASES: Array<[string, number]> = [
  ['рост цен', -2],
  ['рост тарифов', -1.5],
  ['тяжелом состоянии', -2.5],
  ['тяжелое состояние', -2.5],
  ['режим повышенной готовности', -1.5],
  ['не хватает', -1.5],
  ['без пострадавших', 1.5],
  ['снижение налог', 1.5],
  ['снижение цен', 1.5],
  ['снижение ставк', 1.5],
  ['снижение травматизм', 3],
  ['снижение преступност', 3],
  ['снижение смертност', 3],
  ['защиты от', 2.5],
];
const NEGATORS = new Set(['не', 'нет', 'без', 'ни', 'никто', 'ничего', 'нельзя']);

const TITLE_WEIGHT = 1.5;
const LEAD_WEIGHT = 0.7;
const SCALE = 7;

function scoreText(text: string): number {
  const tokens = tokenize(text);
  let raw = 0;
  const seen = new Set<Rule>();
  tokens.forEach((tok, i) => {
    const hit = RULES.find((r) => (r.exact ? tok === r.stem : tok.startsWith(r.stem)));
    if (!hit) return;
    const negated = NEGATORS.has(tokens[i - 1] ?? '') || NEGATORS.has(tokens[i - 2] ?? '');
    let w = hit.weight > 0 ? hit.weight * POSITIVE_DAMP : hit.weight;
    if (seen.has(hit)) w *= REPEAT_DAMP; // то же слово повторно почти не добавляет смысла
    seen.add(hit);
    raw += negated ? -w * 0.7 : w;
  });
  const flat = tokens.join(' ');
  for (const [phrase, w] of PHRASES) if (flat.includes(phrase)) raw += w;
  return raw;
}

export interface SentimentResult {
  score: number;
  label: SentimentLabel;
}

/** Оценка −1…+1 и одна из пяти градаций (пороги — в @mediaradar/core). Нет слов из словаря — 0, «нейтрально». */
export function analyzeSentiment(title: string, lead: string | null): SentimentResult {
  const raw = scoreText(title) * TITLE_WEIGHT + (lead ? scoreText(lead) * LEAD_WEIGHT : 0);
  const score = Math.round(Math.tanh(raw / SCALE) * 100) / 100;
  return { score, label: sentimentFromScore(score) };
}
