type Entry = { stem: string; exact: boolean };
const INDEX: Array<[TopicKey | 'NONE', Entry[]]> = (
  Object.entries(TOPICS) as Array<[TopicKey | 'NONE', string]>
).map(([key, words]) => [
  key,
  words
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => ({ stem: w.replace(/=$/, ''), exact: w.endsWith('=') })),
]);

const PRIORITY: TopicKey[] = ['agro', 'fuel', 'food', 'city', 'econ', 'gov', 'soc'];
const MIN_SCORE = 2;
const TITLE_WEIGHT = 2;

function score(entries: Entry[], tokens: string[]): number {
  let n = 0;
  for (const tok of tokens) if (entries.some((e) => (e.exact ? tok === e.stem : tok.startsWith(e.stem)))) n++;
  return n;
}

/** Ключ темы из пресета или null («без темы»). */
export function analyzeTopic(title: string, lead: string | null): TopicKey | null {
  const t = tokenize(title);
  const l = lead ? tokenize(lead) : [];
  const scores = INDEX.map(
    ([key, entries]) => [key, score(entries, t) * TITLE_WEIGHT + score(entries, l)] as const,
  );
  const none = scores.find(([k]) => k === 'NONE')![1];
  // при равенстве выигрывает более узкая тема; «Общество» — самая общая, поэтому последняя
  const ranked = scores
    .filter(([k]) => k !== 'NONE')
    .sort((a, b) => b[1] - a[1] || PRIORITY.indexOf(a[0] as TopicKey) - PRIORITY.indexOf(b[0] as TopicKey));
  const best = ranked[0]!;
  if (best[1] < MIN_SCORE || none >= best[1]) return null;
  return best[0] as TopicKey;
}
