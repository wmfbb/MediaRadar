/**
 * Загружает словарь в таблицу entities. Идемпотентно: запись находится по (тип, каноническое имя),
 * псевдонимы и должность обновляются, остальные атрибуты не трогаются.
 */
export async function seedRealEntities(client: Queryable): Promise<{ total: number }> {
  for (const e of REAL_ENTITIES) {
    const attrs = { dictionary: true, aliases: e.aliases, ...(e.role ? { role: e.role } : {}) };
    await client.query(
      `INSERT INTO entities (type, canonical_name, is_public_figure, attributes) VALUES ($1, $2, true, $3)
       ON CONFLICT (type, canonical_name) DO UPDATE SET attributes = entities.attributes || EXCLUDED.attributes`,
      [e.type, e.name, JSON.stringify(attrs)],
    );
  }
  return { total: REAL_ENTITIES.length };
}
